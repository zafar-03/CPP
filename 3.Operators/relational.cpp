#include<iostream>

using namespace std;

int main(){

    cout << "Equal to Equal to : " << (11 == 12) << endl;
    cout << "Not Equal to : " << (11 != 12) << endl;
    cout << "Less than : " << (12 < 12) << endl;
    cout << "Less than or Equal to : " << (12 <= 12) << endl;
    cout << "Greater than : " << (13 > 12) << endl;
    cout << "Greater than or Equal to : " << (13 >= 12) << endl;
  
    cout << "Not  : " << !(11!=12) << endl;

    return 0;
}